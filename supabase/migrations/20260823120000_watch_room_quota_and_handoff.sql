create table if not exists public.watch_room_creations (
  id bigint generated by default as identity primary key,
  host_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists watch_room_creations_host_idx on public.watch_room_creations (host_id, created_at desc);

alter table public.watch_room_creations enable row level security;

create or replace function public.watch_room_release(p_actor uuid, p_keep text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target text;
  successor uuid;
begin
  for target in
    select room_code from public.watch_room_members
    where user_id = p_actor and (p_keep is null or room_code <> p_keep)
  loop
    delete from public.watch_room_members
    where room_code = target and user_id = p_actor;

    select user_id into successor from public.watch_room_members
    where room_code = target
    order by joined_at, user_id
    limit 1;

    if successor is null then
      delete from public.watch_rooms where code = target;
    else
      update public.watch_rooms set host_id = successor
      where code = target and host_id = p_actor;
    end if;
  end loop;

  delete from public.watch_rooms r
  where r.host_id = p_actor
    and (p_keep is null or r.code <> p_keep)
    and not exists (select 1 from public.watch_room_members m where m.room_code = r.code);
end;
$$;

create or replace function public.create_watch_room(display_name text default 'Guest')
returns public.watch_rooms
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid := auth.uid();
  limits public.watch_settings;
  candidate text;
  room public.watch_rooms;
begin
  if actor is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  perform public.watch_room_purge();
  delete from public.watch_room_creations where created_at < now() - interval '1 day';

  select * into limits from public.watch_settings where id;

  if (
    select count(*) from public.watch_room_creations
    where host_id = actor and created_at > now() - interval '1 hour'
  ) >= limits.rooms_per_hour then
    raise exception 'room creation limit reached, try again later' using errcode = '53400';
  end if;

  perform public.watch_room_release(actor);

  for attempt in 1..32 loop
    candidate := public.watch_room_code();
    begin
      insert into public.watch_rooms (code, host_id, max_members, expires_at)
      values (candidate, actor, limits.max_members, now() + limits.room_ttl)
      returning * into room;
      exit;
    exception when unique_violation then
      room := null;
    end;
  end loop;

  if room.code is null then
    raise exception 'could not allocate a room code' using errcode = '53400';
  end if;

  insert into public.watch_room_creations (host_id) values (actor);

  insert into public.watch_room_members (room_code, user_id, display_name)
  values (room.code, actor, coalesce(nullif(btrim(display_name), ''), 'Guest'));

  return room;
end;
$$;

create or replace function public.join_watch_room(code text, display_name text default 'Guest')
returns public.watch_rooms
language plpgsql
security definer
set search_path = public
as $$
declare
  actor uuid := auth.uid();
  target text := upper(btrim(code));
  room public.watch_rooms;
begin
  if actor is null then
    raise exception 'authentication required' using errcode = '42501';
  end if;

  select * into room from public.watch_rooms
  where public.watch_rooms.code = target and expires_at > now()
  for update;

  if not found then
    raise exception 'room not found' using errcode = 'P0002';
  end if;

  if exists (
    select 1 from public.watch_room_members
    where room_code = target and user_id = actor
  ) then
    return room;
  end if;

  if (select count(*) from public.watch_room_members where room_code = target) >= room.max_members then
    raise exception 'room is full' using errcode = '53400';
  end if;

  perform public.watch_room_release(actor, target);

  insert into public.watch_room_members (room_code, user_id, display_name)
  values (target, actor, coalesce(nullif(btrim(display_name), ''), 'Guest'));

  return room;
end;
$$;

revoke all on function public.watch_room_release(uuid, text) from public;
revoke all on function public.watch_room_release(uuid, text) from anon;
revoke all on function public.watch_room_release(uuid, text) from authenticated;
revoke all on function public.create_watch_room(text) from public;
revoke all on function public.join_watch_room(text, text) from public;
grant execute on function public.create_watch_room(text) to authenticated;
grant execute on function public.join_watch_room(text, text) to authenticated;
